package paintengine2d

// NewBitmapAtlas packs 5×7 glyphs (designed for this library — not a
// third-party font file) into a premul atlas. Supported runes: space,
// digits, A–Z, and a few punctuation characters used by UI labels.
//
// Missing runes are omitted. Cell size is 6×8 (1 px padding). Advance is 6.
func NewBitmapAtlas(fg Color) *FontAtlas {
	const (
		cw, ch = 6, 8
		cols   = 16
	)
	runes := bitmapRunes()
	rows := (len(runes) + cols - 1) / cols
	img := NewImage(cols*cw, rows*ch)
	cells := make(map[GlyphID]AtlasCell, len(runes))
	for i, r := range runes {
		bits, ok := ascii5x7[r]
		if !ok {
			continue
		}
		col := i % cols
		row := i / cols
		ox, oy := col*cw, row*ch
		for y := 0; y < 7; y++ {
			rowBits := bits[y]
			for x := 0; x < 5; x++ {
				if rowBits&(1<<uint(4-x)) != 0 {
					img.SetColor(ox+x, oy+y, fg)
				}
			}
		}
		id := GlyphID(r)
		cell := AtlasCell{
			Src:     XYWH(float32(ox), float32(oy), cw, ch),
			Advance: cw,
		}
		cells[id] = cell
		// Labels often mix case; alias a–z onto the same A–Z cells.
		if r >= 'A' && r <= 'Z' {
			cells[GlyphID(r-'A'+'a')] = cell
		}
	}
	return &FontAtlas{Image: img, Cells: cells}
}

func bitmapRunes() []rune {
	s := " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-.:!?+/_%()="
	return []rune(s)
}

